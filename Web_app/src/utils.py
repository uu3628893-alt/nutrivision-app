import io
import os
import pandas as pd
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def format_nutrient(value: float, unit: str = "g", decimals: int = 1) -> str:
    # Format floating point nutrient with unit string
    if value is None or pd.isna(value):
        return f"0.0 {unit}"
    return f"{value:.{decimals}f} {unit}"


def format_calorie(value: float) -> str:
    # Format energy value as integer kcal
    if value is None or pd.isna(value):
        return "0 kcal"
    return f"{round(value)} kcal"


def export_meals_to_dataframe(meals: List[Dict[str, Any]]) -> pd.DataFrame:
    # Convert list of meal records to structured DataFrame for CSV export
    records = []
    for m in meals:
        records.append({
            'Meal ID': m.get('id'),
            'Recorded At': str(m.get('created_at', ''))[:16],
            'Meal Name': m.get('meal_name', 'Meal'),
            'Meal Type': m.get('meal_type', 'Meal'),
            'Total Weight (g)': round(m.get('total_grams', 0.0), 1),
            'Calories (kcal)': round(m.get('total_calories', 0.0), 1),
            'Protein (g)': round(m.get('total_protein', 0.0), 1),
            'Carbohydrates (g)': round(m.get('total_carbs', 0.0), 1),
            'Fat (g)': round(m.get('total_fat', 0.0), 1),
            'Fiber (g)': round(m.get('total_fiber', 0.0), 1),
            'Sugar (g)': round(m.get('total_sugars', 0.0), 1),
            'Sodium (mg)': round(m.get('total_sodium', 0.0), 1),
            'Notes': m.get('notes', '')
        })
    return pd.DataFrame(records)


def generate_nutritional_pdf_report(
    profile: Dict[str, Any],
    meal_summary: Dict[str, Any],
    ingredients: List[Dict[str, Any]],
    recommendations: List[Any]
) -> bytes:
    # Render downloadable PDF clinical summary report using ReportLab
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()

    # Custom academic styles
    title_style = ParagraphStyle(
        'RepTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#1f4e79')
    )
    section_style = ParagraphStyle(
        'RepSection',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#2c3e50')
    )
    body_style = ParagraphStyle(
        'RepBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=13,
        textColor=colors.HexColor('#333333')
    )

    story = []

    # Title block
    story.append(Paragraph("NutriVision Nutritional Assessment Report", title_style))
    story.append(Spacer(1, 10))
    story.append(Paragraph("Generated by AI-Powered Nutritional Analysis and Dietary Recommendation System", body_style))
    story.append(Spacer(1, 15))

    # User Profile Section
    story.append(Paragraph("1. Subject Profile & Daily Targets", section_style))
    story.append(Spacer(1, 6))

    bmi_val = profile.get('bmi', 'N/A')
    bmi_str = f"{bmi_val:.1f}" if isinstance(bmi_val, (int, float)) else str(bmi_val)
    bmi_cat = profile.get('bmi_category', '')

    prof_data = [
        ["Age / Sex", f"{profile.get('age', 'N/A')} yrs / {profile.get('sex', 'N/A')}", "Height / Weight", f"{profile.get('height_cm', 'N/A')} cm / {profile.get('weight_kg', 'N/A')} kg"],
        ["BMI", f"{bmi_str} ({bmi_cat})" if bmi_cat else bmi_str, "Activity Level", str(profile.get('activity_level', 'N/A'))],
        ["Target Energy", f"{round(profile.get('target_calories', 0))} kcal", "Dietary Goal", str(profile.get('goal', 'N/A')).title()],
        ["Allergies", str(profile.get('allergies', 'None')) or "None", "Preferences", str(profile.get('preferences', 'None')) or "None"]
    ]
    t_prof = Table(prof_data, colWidths=[110, 150, 110, 150])
    t_prof.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8f9fa')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#2c3e50')),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME', (2, 0), (2, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7de')),
    ]))
    story.append(t_prof)
    story.append(Spacer(1, 15))

    # Meal Nutrition Section
    story.append(Paragraph("2. Meal Nutritional Composition", section_style))
    story.append(Spacer(1, 6))

    cals = meal_summary.get('calories_kcal', meal_summary.get('energy_kcal', 0.0))
    prot = meal_summary.get('protein_g', 0.0)
    carbs = meal_summary.get('carbs_g', meal_summary.get('carbohydrate_g', 0.0))
    fat = meal_summary.get('fat_g', 0.0)
    fiber = meal_summary.get('fiber_g', meal_summary.get('dietary_fiber_g', 0.0))
    sugar = meal_summary.get('sugars_g', meal_summary.get('sugars_total_g', 0.0))
    sodium = meal_summary.get('sodium_mg', 0.0)

    nutr_data = [
        ["Nutrient Parameter", "Assessed Value", "Nutrient Parameter", "Assessed Value"],
        ["Total Calories", f"{round(cals)} kcal", "Dietary Fiber", f"{fiber:.1f} g"],
        ["Protein", f"{prot:.1f} g", "Total Sugars", f"{sugar:.1f} g"],
        ["Carbohydrates", f"{carbs:.1f} g", "Sodium", f"{sodium:.0f} mg"],
        ["Total Fat", f"{fat:.1f} g", "", ""]
    ]
    t_nutr = Table(nutr_data, colWidths=[130, 130, 130, 130])
    t_nutr.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1f4e79')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7de')),
    ]))
    story.append(t_nutr)
    story.append(Spacer(1, 15))

    # Ingredients Breakdown Section
    if ingredients:
        story.append(Paragraph("3. Identified Food Ingredients & Portions", section_style))
        story.append(Spacer(1, 6))
        ing_data = [["Ingredient", "Portion Description", "Weight (g)", "Calories (kcal)", "Protein (g)"]]
        for ing in ingredients:
            fname = str(ing.get('food_name', 'Item'))[:30]
            pdesc = str(ing.get('portion_name', ing.get('portion_description', 'Serving')))[:25]
            w_g = ing.get('grams', ing.get('weight_g', 0.0))
            ing_cal = ing.get('calories', ing.get('calories_kcal', ing.get('energy_kcal', 0.0)))
            ing_p = ing.get('protein', ing.get('protein_g', 0.0))
            ing_data.append([
                fname.title(),
                pdesc,
                f"{w_g:.1f}",
                f"{round(ing_cal)}",
                f"{ing_p:.1f}"
            ])
        t_ing = Table(ing_data, colWidths=[150, 150, 60, 80, 80])
        t_ing.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#2c3e50')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8.5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#d0d7de')),
        ]))
        story.append(t_ing)
        story.append(Spacer(1, 15))

    # Personalized Recommendations Section
    if recommendations:
        story.append(Paragraph("4. Automated Personalized Dietary Recommendations", section_style))
        story.append(Spacer(1, 6))
        for r in recommendations:
            if isinstance(r, dict):
                cat = r.get('category', 'Dietary Note')
                rec_text = r.get('text', '')
                story.append(Paragraph(f"• <b>[{cat}]</b> {rec_text}", body_style))
            else:
                story.append(Paragraph(f"• {str(r)}", body_style))
            story.append(Spacer(1, 3))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
